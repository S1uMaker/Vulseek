import { execFile } from "node:child_process";
import { createServer, type IncomingMessage, type Server } from "node:http";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

const cliPath = join(
	dirname(fileURLToPath(import.meta.url)),
	"../../../../../agents/skills/hunt-ledger/hunt_ledger.py",
);

type MockRequest = {
	method?: string;
	url?: string;
	body: string;
};

const startMockApi = async (
	handler: (req: MockRequest) => { status: number; body: unknown },
) => {
	const server: Server = createServer((req: IncomingMessage, res) => {
		const chunks: Buffer[] = [];
		req.on("data", (chunk) => {
			chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
		});
		req.on("end", () => {
			const result = handler({
				method: req.method,
				url: req.url,
				body: Buffer.concat(chunks).toString("utf8"),
			});
			res.statusCode = result.status;
			res.setHeader("content-type", "application/json");
			res.end(JSON.stringify(result.body));
		});
	});
	await new Promise<void>((resolve) => {
		server.listen(0, "127.0.0.1", () => resolve());
	});
	const address = server.address();
	if (!address || typeof address === "string") {
		throw new Error("mock API did not bind a port");
	}
	return {
		url: `http://127.0.0.1:${address.port}`,
		close: () =>
			new Promise<void>((resolve, reject) => {
				server.close((error) => (error ? reject(error) : resolve()));
			}),
	};
};

const runtimeEnv = {
	VULSEEK_SCAN_JOB_ID: "job-1",
	VULSEEK_TASK_ID: "hunter-1",
	VULSEEK_STAGE_NAME: "hunter",
};

const runCli = (
	args: string[],
	stdin?: string,
): Promise<{ stdout: string; stderr: string }> =>
	new Promise((resolve, reject) => {
		const child = execFile(
			"python3",
			[cliPath, ...args],
			{ env: { ...process.env, ...runtimeEnv } },
			(error, stdout, stderr) => {
				if (error) {
					(
						error as {
							stdout?: string;
							stderr?: string;
						}
					).stdout = String(stdout);
					(
						error as {
							stdout?: string;
							stderr?: string;
						}
					).stderr = String(stderr);
					reject(error);
					return;
				}
				resolve({ stdout: String(stdout), stderr: String(stderr) });
			},
		);
		if (stdin !== undefined) {
			child.stdin?.write(stdin);
		}
		child.stdin?.end();
	});

describe("hunt-ledger CLI", () => {
	const servers: Array<{ close: () => Promise<void> }> = [];

	afterEach(async () => {
		await Promise.all(servers.splice(0).map((server) => server.close()));
	});

	it.each(["create-gate", "create-ledger"])(
		"rejects entry.id in %s before contacting the API",
		async (command) => {
			const entry = {
				id: 42,
				title: "Test gate",
				statement: "test",
				type: "gate",
			};
			const body =
				command === "create-ledger" ? { action: "create", entry } : entry;
			await expect(
				runCli([command], JSON.stringify(body)),
			).rejects.toMatchObject({
				stdout: expect.stringContaining(
					"entry.id is generated by the database",
				),
			});
		},
	);

	it.each(["custom-id", "0", "-1", "1.5", "2147483648"])(
		"rejects non-integer or out-of-range --id %s",
		async (id) => {
			await expect(runCli(["get-ledger", "--id", id])).rejects.toMatchObject({
				stderr: expect.stringContaining("id must be"),
			});
		},
	);

	it("injects type for create-gate", async () => {
		const requests: MockRequest[] = [];
		const api = await startMockApi((req) => {
			requests.push(req);
			if (req.url?.includes("/ledger") && req.method === "POST") {
				const body = JSON.parse(req.body);
				expect(body).toEqual({
					action: "create",
					entry: {
						title: "REST author exclusion input type",
						statement: "REST author_exclude is an int array",
						type: "gate",
					},
				});
				expect(body.entry.scanJobId).toBeUndefined();
				return {
					status: 200,
					body: { ok: true, entry: { id: 1, type: "gate" } },
				};
			}
			return { status: 404, body: { ok: false } };
		});
		servers.push(api);
		const { stdout } = await runCli(
			["create-gate", "--api-url", api.url, "--token", "test-token"],
				JSON.stringify({
					title: "REST author exclusion input type",
					statement: "REST author_exclude is an int array",
				}),
		);
		expect(JSON.parse(stdout)).toMatchObject({
			ok: true,
			entry: { id: 1 },
		});
	});

	it("rejects get-sink when the row is a gate", async () => {
		const api = await startMockApi((req) => {
			if (req.url?.includes("/ledger") && req.method === "GET") {
				return {
					status: 200,
					body: {
						ok: true,
						entry: {
							id: 1,
							title: "Login gate",
							type: "gate",
							statement: "login check",
						},
					},
				};
			}
			return { status: 404, body: { ok: false } };
		});
		servers.push(api);
		await expect(
			runCli([
				"get-sink",
				"--id",
				"1",
				"--api-url",
				api.url,
				"--token",
				"test-token",
			]),
		).rejects.toMatchObject({
			stdout: expect.stringContaining("VALIDATION_ERROR"),
		});
	});

	it("wraps append-evidence as a single update operation", async () => {
		const requests: MockRequest[] = [];
		const api = await startMockApi((req) => {
			requests.push(req);
			if (req.url?.includes("/ledger") && req.method === "POST") {
				expect(JSON.parse(req.body)).toEqual({
					action: "update",
					entryId: 1,
					expectedRevision: 2,
					reason: "add code evidence",
					operations: [
						{
							op: "append_evidence",
							value: {
								id: "ev-1",
								kind: "code",
								stance: "supports",
								summary: "filename comes from query",
								ref: { file: "src/download.ts", line: 12 },
							},
						},
					],
				});
				return {
					status: 200,
					body: { ok: true, entry: { id: 1, revision: 3 } },
				};
			}
			return { status: 404, body: { ok: false } };
		});
		servers.push(api);
		const { stdout } = await runCli(
			[
				"append-evidence",
				"--id",
				"1",
				"--expected-revision",
				"2",
				"--reason",
				"add code evidence",
				"--api-url",
				api.url,
				"--token",
				"test-token",
			],
			JSON.stringify({
				id: "ev-1",
				kind: "code",
				stance: "supports",
				summary: "filename comes from query",
				ref: { file: "src/download.ts", line: 12 },
			}),
		);
		expect(JSON.parse(stdout)).toMatchObject({
			ok: true,
			entry: { revision: 3 },
		});
		expect(requests).toHaveLength(1);
	});

	it("wraps set-state and forwards Ledger filters", async () => {
		const requests: MockRequest[] = [];
		const api = await startMockApi((req) => {
			requests.push(req);
			if (req.method === "GET") {
				expect(req.url).toContain("state=assigned");
				expect(req.url).toContain("functionName=WP_Query%3A%3Aget_posts");
				return { status: 200, body: { ok: true, entries: [] } };
			}
			if (req.method === "POST") {
				expect(JSON.parse(req.body)).toEqual({
					action: "update",
					entryId: 1,
					expectedRevision: 2,
					reason: "dispatch hunter",
					operations: [
						{
							op: "set_state",
							state: "assigned",
							reason: "dispatch hunter",
						},
					],
				});
				return { status: 200, body: { ok: true, entry: { id: 1 } } };
			}
			return { status: 404, body: { ok: false } };
		});
		servers.push(api);

		await runCli([
			"list-ledger",
				"--state",
				"assigned",
				"--function-name",
				"WP_Query::get_posts",
			"--api-url",
			api.url,
			"--token",
			"test-token",
		]);
		const { stdout } = await runCli([
			"set-state",
			"--id",
			"1",
			"--expected-revision",
			"2",
			"--state",
			"assigned",
			"--reason",
			"dispatch hunter",
			"--api-url",
			api.url,
			"--token",
			"test-token",
		]);
		expect(JSON.parse(stdout)).toMatchObject({ ok: true });
		expect(requests).toHaveLength(2);
	});

	it("prints REVISION_CONFLICT JSON on stdout and exits non-zero", async () => {
		const api = await startMockApi(() => ({
			status: 409,
			body: {
				ok: false,
				code: "REVISION_CONFLICT",
				error: "Ledger entry revision conflict",
				current: { id: 1, revision: 4 },
			},
		}));
		servers.push(api);
		await expect(
			runCli(
				[
					"update-ledger",
					"--id",
					"1",
					"--expected-revision",
					"1",
					"--reason",
					"stale",
					"--api-url",
					api.url,
					"--token",
					"test-token",
				],
				JSON.stringify({
					reason: "stale",
					operations: [
						{
							op: "append_gap",
							value: { id: "gap-1", question: "still open?" },
						},
					],
				}),
			),
		).rejects.toMatchObject({
			stdout: expect.stringContaining("REVISION_CONFLICT"),
		});
	});
});
