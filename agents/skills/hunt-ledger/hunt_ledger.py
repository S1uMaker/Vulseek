#!/usr/bin/env python3
"""Read and write Vulseek hunt-ledger entries via the internal HTTP API."""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any


def load_runtime_api() -> Any:
    path = (
        Path(__file__).resolve().parent.parent
        / "scan-runtime"
        / "runtime_api.py"
    )
    spec = importlib.util.spec_from_file_location("runtime_api", path)
    if spec is None or spec.loader is None:
        print(f"hunt-ledger failed: cannot load {path}", file=sys.stderr)
        raise SystemExit(1)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.set_tool_name("hunt-ledger")
    return module


runtime = load_runtime_api()
fail = runtime.fail
emit_json = runtime.emit_json
read_json_stdin = runtime.read_json_stdin
runtime_request = runtime.runtime_request
add_runtime_flags = runtime.add_runtime_flags

LEDGER_PATH = "/api/internal/scan/runtime/ledger"
LEDGER_ENTRY_TYPES = (
    "source",
    "sink",
    "gate",
    "connector",
    "impact",
    "hypothesis",
)
LEDGER_TYPE_PLURALS = {
    "source": "sources",
    "sink": "sinks",
    "gate": "gates",
    "connector": "connectors",
    "impact": "impacts",
    "hypothesis": "hypotheses",
}
LEDGER_VERDICTS = ("unknown", "supported", "refuted", "contested")
LEDGER_STATES = (
    "untracked",
    "discovered",
    "assigned",
    "investigating",
    "partial",
    "covered",
    "blocked",
)
LEDGER_GAP_STATUSES = ("open", "investigating", "resolved", "blocked")


def _validation_error(message: str) -> None:
    emit_json({"ok": False, "code": "VALIDATION_ERROR", "error": message}, 1)


def ledger_entry_id(value: str) -> int:
    if not value.isascii() or not value.isdecimal():
        raise argparse.ArgumentTypeError(
            "id must be a positive integer; use list-ledger to obtain current database IDs"
        )
    entry_id = int(value)
    if not 1 <= entry_id <= 2_147_483_647:
        raise argparse.ArgumentTypeError("id must be between 1 and 2147483647")
    return entry_id


def _entry_from_payload(payload: Any) -> dict[str, Any] | None:
    if not isinstance(payload, dict):
        return None
    entry = payload.get("entry")
    if isinstance(entry, dict):
        return entry
    return None


def _assert_entry_type(payload: Any, expected_type: str | None) -> None:
    if not expected_type:
        return
    entry = _entry_from_payload(payload)
    actual = entry.get("type") if entry else None
    if actual != expected_type:
        _validation_error(
            f"ledger entry type is {actual!r}, expected {expected_type!r}"
        )


def list_ledger(args: argparse.Namespace) -> None:
    query: dict[str, str] = {}
    entry_id = getattr(args, "id", None)
    if entry_id is not None:
        query["id"] = str(entry_id)
    ledger_type = str(getattr(args, "type", "") or "").strip()
    if ledger_type:
        query["type"] = ledger_type
    verdict = str(getattr(args, "verdict", "") or "").strip()
    if verdict:
        query["verdict"] = verdict
    state = str(getattr(args, "state", "") or "").strip()
    if state:
        query["state"] = state
    title = str(getattr(args, "title", "") or "").strip()
    if title:
        query["title"] = title
    function_name = str(getattr(args, "function_name", "") or "").strip()
    if function_name:
        query["functionName"] = function_name
    file_prefix = str(getattr(args, "file", "") or "").strip()
    if file_prefix:
        query["file"] = file_prefix
    if getattr(args, "unlinked_sinks", False):
        query["unlinkedSinks"] = "1"
    if getattr(args, "include_other_snapshots", False):
        query["includeOtherSnapshots"] = "1"
    payload = runtime_request(args, LEDGER_PATH, query=query or None)
    if entry_id:
        _assert_entry_type(payload, getattr(args, "expected_type", None))
    emit_json(payload)


def get_ledger(args: argparse.Namespace) -> None:
    if getattr(args, "id", None) is None:
        fail("--id is required")
    list_ledger(args)


def create_ledger(args: argparse.Namespace) -> None:
    body = getattr(args, "create_body", None)
    if body is None:
        body = read_json_stdin()
    if not isinstance(body, dict) or body.get("action") != "create":
        fail('create-ledger stdin must be { "action": "create", "entry": { ... } }')
    if not isinstance(body.get("entry"), dict):
        fail("create-ledger entry must be an object")
    if "id" in body["entry"]:
        _validation_error("entry.id is generated by the database; omit it on create")
    emit_json(runtime_request(args, LEDGER_PATH, method="POST", json_body=body))


def create_typed_ledger(args: argparse.Namespace) -> None:
    entry = read_json_stdin()
    if not isinstance(entry, dict):
        fail("typed create stdin must be a primitive object")
    function_id = entry.get("functionId")
    if not isinstance(function_id, int) or isinstance(function_id, bool):
        fail("functionId is required and must be the function row id")
    expected = str(getattr(args, "inject_type", "") or "").strip()
    if expected not in LEDGER_ENTRY_TYPES:
        fail("typed create is missing a valid injected type")
    if entry.get("type") not in (None, expected):
        fail(f"type must be {expected} or omitted")
    body = {key: value for key, value in entry.items() if key != "functionId"}
    body["type"] = expected
    body["action"] = "append-primitive"
    emit_json(
        runtime_request(
            args,
            LEDGER_PATH,
            method="POST",
            query={"id": str(function_id)},
            json_body=body,
        )
    )


def update_ledger(args: argparse.Namespace) -> None:
    entry_id = getattr(args, "id", None)
    if entry_id is None:
        fail("--id is required")
    expected_revision = getattr(args, "expected_revision", None)
    if expected_revision is None:
        fail("--expected-revision is required")
    primitive_id = str(getattr(args, "primitive_id", "") or "").strip()
    if not primitive_id:
        fail("--primitive-id is required")
    body = getattr(args, "update_body", None)
    if body is None:
        body = read_json_stdin()
    if not isinstance(body, dict):
        fail("update-ledger stdin must be an object")
    reason = getattr(args, "reason", None) or body.get("reason")
    operations = body.get("operations")
    if not isinstance(reason, str) or not reason.strip():
        fail("reason is required")
    if not isinstance(operations, list) or not operations:
        fail("operations must be a non-empty array")
    emit_json(
        runtime_request(
            args,
            LEDGER_PATH,
            method="POST",
            query={"id": str(entry_id)},
            json_body={
                "action": "update-primitive",
                "functionId": entry_id,
                "primitiveId": primitive_id,
                "expectedRevision": int(expected_revision),
                "reason": reason.strip(),
                "operations": operations,
            },
        )
    )


def ensure_function(args: argparse.Namespace) -> None:
    body: dict[str, Any] = {
        "action": "ensure-function",
        "file": args.file,
        "functionName": args.function_name,
        "line": args.line,
    }
    if args.end_line is not None:
        body["endLine"] = args.end_line
    emit_json(runtime_request(args, LEDGER_PATH, method="POST", json_body=body))


def assign_function(args: argparse.Namespace) -> None:
    emit_json(
        runtime_request(
            args,
            LEDGER_PATH,
            method="POST",
            query={"id": str(args.id)},
            json_body={
                "action": "assign-function",
                "expectedRevision": args.expected_revision,
                "reason": args.reason,
            },
        )
    )


def append_primitive_cmd(args: argparse.Namespace) -> None:
    primitive = read_json_stdin()
    if not isinstance(primitive, dict):
        fail("append-primitive stdin must be an object")
    if args.type not in LEDGER_ENTRY_TYPES:
        fail(f"type must be one of {', '.join(LEDGER_ENTRY_TYPES)}")
    primitive = {**primitive, "type": args.type, "expectedRevision": args.expected_revision}
    primitive.pop("functionId", None)
    emit_json(
        runtime_request(
            args,
            LEDGER_PATH,
            method="POST",
            query={"id": str(args.id)},
            json_body={"action": "append-primitive", **primitive},
        )
    )


def set_function_state(args: argparse.Namespace) -> None:
    emit_json(
        runtime_request(
            args,
            LEDGER_PATH,
            method="POST",
            query={"id": str(args.id)},
            json_body={
                "action": "set-function-state",
                "state": args.state,
                "expectedRevision": args.expected_revision,
                "reason": args.reason,
            },
        )
    )


def _update_with_operation(
    args: argparse.Namespace,
    operation: dict[str, Any],
    reason: str,
) -> None:
    args.update_body = {
        "reason": reason,
        "operations": [operation],
    }
    update_ledger(args)


