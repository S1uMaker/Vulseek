def set_gap(args: argparse.Namespace) -> None:
    gap_id = str(getattr(args, "gap_id", "") or "").strip()
    status = str(getattr(args, "status", "") or "").strip()
    reason = str(getattr(args, "reason", "") or "").strip()
    if not gap_id:
        fail("--gap-id is required")
    if status not in LEDGER_GAP_STATUSES:
        fail("status must be open, investigating, resolved, or blocked")
    if not reason:
        fail("--reason is required")
    operation: dict[str, Any] = {
        "op": "set_gap",
        "gapId": gap_id,
        "status": status,
    }
    result = str(getattr(args, "result", "") or "").strip()
    result_refs_raw = str(getattr(args, "result_refs", "") or "").strip()
    stdin_payload: Any = None
    if not sys.stdin.isatty():
        raw = sys.stdin.read()
        if raw.strip():
            try:
                stdin_payload = json.loads(raw)
            except json.JSONDecodeError as exc:
                fail(f"stdin is not valid JSON: {exc}")
    if isinstance(stdin_payload, dict):
        if not result and isinstance(stdin_payload.get("result"), str):
            result = stdin_payload["result"].strip()
        if not result_refs_raw and "resultRefs" in stdin_payload:
            result_refs_raw = json.dumps(stdin_payload["resultRefs"])
    if status in ("open", "investigating"):
        if result or result_refs_raw:
            fail("open/investigating cannot include result or resultRefs")
    elif status == "resolved":
        if not result:
            fail("resolved requires --result")
        if not result_refs_raw:
            fail("resolved requires --result-refs or stdin resultRefs")
        try:
            result_refs = json.loads(result_refs_raw)
        except json.JSONDecodeError as exc:
            fail(f"resultRefs is not valid JSON: {exc}")
        if not isinstance(result_refs, list) or not result_refs:
            fail("resolved resultRefs must be a non-empty array")
        operation["result"] = result
        operation["resultRefs"] = result_refs
    else:
        if not result:
            fail("blocked requires --result")
        operation["result"] = result
        if result_refs_raw:
            try:
                result_refs = json.loads(result_refs_raw)
            except json.JSONDecodeError as exc:
                fail(f"resultRefs is not valid JSON: {exc}")
            if not isinstance(result_refs, list):
                fail("resultRefs must be an array")
            operation["resultRefs"] = result_refs
    _update_with_operation(args, operation, reason)


